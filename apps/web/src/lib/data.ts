// Catalog seed data. Slugs (id) are kept in sync with apps/api/app/services/catalog.py
// so checkout price-validation matches. Computers span budget → high-end (UGX 550k+).

export type ProductDetails = {
  type: string; // e.g. Business Ultrabook, Gaming Laptop, Desktop Tower
  processor: string; // full CPU incl. i-Core / Ryzen model
  generation: string; // e.g. 11th Gen, Apple M1
  ram: string; // size + type
  storage: string; // size + type (SSD/HDD)
  graphics: string; // integrated or dedicated GPU
  display: string; // size + resolution
  os: string; // Windows / macOS
  battery: string; // battery life
  ports: string; // ports & connectivity
  build: string; // build quality
  purpose: string; // what the machine is best for
};

export type Product = {
  id: string;
  name: string;
  category: "Laptops" | "Desktops" | "Components" | "Power" | "Accessories" | "Networking" | "Storage";
  price: number; // UGX
  oldPrice?: number;
  brand: string;
  condition: "Brand New" | "UK Used" | "Refurbished";
  rating: number;
  badge?: string;
  inStock?: boolean; // defaults to true when omitted
  image?: string; // remote/web image URL; falls back to /products/<id>.webp
  specs: string[]; // short bullets for cards/grid
  details?: ProductDetails; // full specification (computers)
};

// Resolve a product's image: an explicit web URL if provided, else the local
// curated photo by slug convention.
export function productImage(p: Pick<Product, "id" | "image">): string {
  return p.image ?? `/products/${p.id}.webp`;
}

