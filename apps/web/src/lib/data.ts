// Per-lesson unlock price (UGX), 5,000-15,000 by lesson length. Lessons now
// run 30-90 minutes, so the bands are set against that range.
export function lessonPrice(minutes: number): number {
  if (minutes <= 30) return 5000;
  if (minutes <= 45) return 8000;
  if (minutes <= 60) return 10000;
  if (minutes <= 75) return 12000;
  return 15000;
}

